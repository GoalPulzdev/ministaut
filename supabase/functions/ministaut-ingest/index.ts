import 'jsr:@supabase/functions-js/edge-runtime.d.ts';
import { createClient } from 'npm:@supabase/supabase-js@2.95.0';
const url = Deno.env.get('SUPABASE_URL')!;
const key = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!;
const admin = createClient(url, key, { auth: { persistSession: false } });
const cors = { 'Content-Type': 'application/json', 'Access-Control-Allow-Origin': '*', 'Access-Control-Allow-Headers': 'content-type,x-ministaut-token' };
const reply=(status:number,body:unknown)=>new Response(JSON.stringify(body),{status,headers:cors});
const validKey=/^[A-Za-z0-9_-]{8,100}$/;
Deno.serve(async(req)=>{
  if(req.method==='OPTIONS')return new Response(null,{headers:cors});
  if(req.method!=='POST')return reply(405,{error:'POST required'});
  const raw=req.headers.get('x-ministaut-token')||'';
  if(!/^[a-f0-9]{64}$/.test(raw)&& !/^[A-Za-z0-9_-]{30,200}$/.test(raw))return reply(401,{error:'Unauthorized'});
  const digest=Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',new TextEncoder().encode(raw)))).map(x=>x.toString(16).padStart(2,'0')).join('');
  const {data:token,error:tokenError}=await admin.from('ministaut_scanner_tokens').select('token_name').eq('token_hash',digest).eq('enabled',true).maybeSingle();
  if(tokenError||!token)return reply(401,{error:'Unauthorized'});
  const payload=await req.json().catch(()=>null);
  if(!payload||typeof payload!=='object')return reply(400,{error:'Invalid JSON'});
  const eventKey=String(payload.event_key||'');
  if(!validKey.test(eventKey))return reply(422,{error:'Invalid event ID'});
  const runId=String(payload.source_run_id||'');
  if(!/^[A-Za-z0-9_.:-]{5,160}$/.test(runId))return reply(422,{error:'Invalid run ID'});
  const title=String(payload.title||'Rosenborg – kampstatus').slice(0,120);
  const when=Date.parse(String(payload.observed_at||''));
  if(!Number.isFinite(when)||when>Date.now()+300000)return reply(422,{error:'Invalid timestamp'});
  const sections=payload.sections;
  const locks=payload.locked_fields;
  if(!Array.isArray(sections)||!Array.isArray(locks)||locks.length>2)return reply(422,{error:'Invalid section data'});
  const {data:reference,error:referenceError}=await admin.from('ministaut_sections').select('section_code,capacity');
  if(referenceError||!reference||reference.length!==60)return reply(503,{error:'Stadium reference missing'});
  const ref=new Map(reference.map(s=>[s.section_code,s.capacity]));
  const uniqueLocks=new Set(locks);
  if(uniqueLocks.size!==locks.length||locks.some((s:unknown)=>typeof s!=='string'||!ref.has(s)))return reply(422,{error:'Invalid locks'});
  const seen=new Set<string>();let sum=0;
  for(const s of sections){if(!s||typeof s.section!=='string'||!ref.has(s.section)||uniqueLocks.has(s.section)||seen.has(s.section)||!Number.isInteger(s.free)||s.free<0||s.free>ref.get(s.section)||s.capacity!==ref.get(s.section))return reply(422,{error:'Bad section measurement'});seen.add(s.section);sum+=s.free;}
  if(seen.size+uniqueLocks.size!==60||[...ref.keys()].some(s=>!seen.has(s)&&!uniqueLocks.has(s)))return reply(422,{error:'Incomplete coverage'});
  if(sum!==payload.available_seated||payload.total_capacity!==21423)return reply(422,{error:'Summary mismatch'});
  if(payload.quality_approved!==true||payload.locked_fields_confirmed!==true)return reply(422,{error:'Unapproved scan'});
  const kickoff=payload.kickoff_at?new Date(payload.kickoff_at).toISOString():null;
  // Scanner submissions create new match records but must never overwrite operator-curated metadata.
  const {error:seedError}=await admin.from('ministaut_matches').upsert({event_key:eventKey,title,kickoff_at:kickoff,total_capacity:21423},{onConflict:'event_key',ignoreDuplicates:true});
  if(seedError)return reply(500,{error:'Could not create match'});
  const {data:match,error:matchError}=await admin.from('ministaut_matches').select('id').eq('event_key',eventKey).single();
  if(matchError||!match)return reply(500,{error:'Could not find match'});
  const {data:scan,error:scanError}=await admin.from('ministaut_scans').upsert({match_id:match.id,source_run_id:runId,observed_at:new Date(when).toISOString(),available_seated:sum,counted_sections:seen.size,locked_fields:locks,standing_status:'unknown'},{onConflict:'match_id,source_run_id'}).select('id').single();
  if(scanError)return reply(500,{error:'Could not save scan'});
  const {error:sectionError}=await admin.from('ministaut_section_measurements').upsert(sections.map((s:any)=>({scan_id:scan.id,section_code:s.section,free:s.free,capacity:s.capacity})),{onConflict:'scan_id,section_code'});
  if(sectionError)return reply(500,{error:'Scan saved but section detail failed'});
  return reply(200,{ok:true,scan_id:scan.id,available_seated:sum,estimated_unavailable:21423-sum});
});